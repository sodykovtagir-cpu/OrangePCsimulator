#!/usr/bin/env python3
"""Copy hand-authored CablePort geometry and socket markers to prefab families.

Idempotent: existing CablePorts are never replaced. For ports generated by this
script, copy the author's Conector/Cube visual markers (including their mesh and
collider) without touching ports the designer manually placed on the target.
Unity Play Mode is still needed to visually confirm fit on different models.
"""
from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1] / 'Assets/Resources/components'
PORT_GUID = '1f65810bece34620913cb00d28b91845'
# RTX 3080, not RTX 3090, is the authored RTX reference in this project.
FAMILIES = {
    'RTX3080': ('RTX3080Ti',),  # 2080/2080Ti already have authored ports
    'GTX1060': ('GTX1070', 'GTX1070Ti', 'GTX1080', 'GTX1080Ti', 'Titan V'),
    'GT1030': ('GT1031',),
    'PSU 300W': ('PSU 500W', 'PSU 1kW', 'PSU 1.1kW', 'KSAS PSU'),
    'ATX': ('ATX 2', 'EATX', 'EXATX', 'Micro_ATX', 'MSG_ATX_Black', 'MSG_ATX_White'),
    'Monitor(Black)': ('Monitor(White)',),
    'Monitor 2(White)': ('Monitor 2(Blue)', 'Monitor 2(Green)',
                         'Monitor 2(Red)', 'Monitor 2(Yellow)'),
}
HEADER = re.compile(r'^--- !u!(\d+) &(-?\d+)(?: stripped)?$', re.M)
REFERENCE = re.compile(r'\{fileID: (-?\d+)\}')


def blocks(text):
    starts = list(HEADER.finditer(text))
    return {m.group(2): (int(m.group(1)), text[m.start():starts[i+1].start() if i+1 < len(starts) else len(text)])
            for i, m in enumerate(starts)}


def field(text, key):
    found = re.search(r'^  ' + re.escape(key) + r': (.*)$', text, re.M)
    if found is None:
        raise ValueError('missing ' + key)
    return found.group(1)


def reference(text, key):
    found = re.fullmatch(r'\{fileID: (-?\d+)\}', field(text, key))
    if found is None:
        raise ValueError('bad reference ' + key)
    return found.group(1)


def root_and_owner(docs, name):
    roots = [(fid, text) for fid, (cid, text) in docs.items()
             if cid in (4, 224) and re.search(r'^  m_Father: \{fileID: 0\}$', text, re.M)]
    if len(roots) != 1:
        raise ValueError(name + ': expected one prefab root')
    root_id, root_text = roots[0]
    go_id = reference(root_text, 'm_GameObject')
    components = re.findall(r'^  - component: \{fileID: (-?\d+)\}$', docs[go_id][1], re.M)
    owners = [fid for fid in components if fid in docs and
              re.search(r'^  spawnId: (.*)$', docs[fid][1], re.M)]
    if len(owners) != 1:
        raise ValueError(name + ': expected exactly one root Item')
    return root_id, owners[0]


def authored_ports(docs):
    result = {}
    for fid, (cid, text) in docs.items():
        if cid != 114 or f'guid: {PORT_GUID}' not in text:
            continue
        go_id = reference(text, 'm_GameObject')
        go_text = docs[go_id][1]
        result[field(go_text, 'm_Name')] = (go_id, fid)
    return result


def new_ids(used, target, name):
    ids = []
    for part in ('go', 'transform', 'trigger', 'port', 'pivot-go', 'pivot-transform'):
        salt = 0
        while True:
            digest = hashlib.sha256(f'{target}/{name}/{part}/{salt}'.encode()).digest()
            fid = str(int.from_bytes(digest[:8], 'big') % (2**62 - 1) + 10**16)
            if fid not in used:
                used.add(fid)
                ids.append(fid)
                break
            salt += 1
    return ids


def clone_doc(doc, old_id, new_id, mappings):
    result = re.sub(r'(?m)^--- !u!(\d+) &' + re.escape(old_id) + r'(?=(?: stripped)?\s*$)',
                    lambda m: '--- !u!' + m.group(1) + ' &' + new_id, doc, count=1)
    if result == doc:
        raise ValueError('missing document header ' + old_id)
    result = REFERENCE.sub(lambda m: '{fileID: ' + mappings.get(m.group(1), m.group(1)) + '}', result)
    # Unity source YAML often has blank scalar fields with a trailing space.
    # Avoid introducing new whitespace errors in the copied blocks.
    return re.sub(r'(?m) +$', '', result)


def replicate(source, target):
    source_text = (ROOT / (source + '.prefab')).read_text()
    path = ROOT / (target + '.prefab')
    text = path.read_text()
    src = blocks(source_text)
    dst = blocks(text)
    src_root, src_owner = root_and_owner(src, source)
    dst_root, dst_owner = root_and_owner(dst, target)
    if reference(dst[dst_owner][1], 'm_GameObject') != reference(dst[dst_root][1], 'm_GameObject'):
        raise ValueError(target + ': root Item not on root GameObject')
    source_script = field(src[src_owner][1], 'm_Script')
    target_script = field(dst[dst_owner][1], 'm_Script')
    if source_script != target_script:
        raise ValueError(f'{source} and {target}: different Item types')
    old = authored_ports(src)
    existing = authored_ports(dst)
    used = set(dst)
    appended = []
    added = []
    root_text = dst[dst_root][1]
    for name, (go, port) in old.items():
        if name in existing:
            continue  # preserve all ports already manually authored in target
        if re.search(r'^  m_Name: ' + re.escape(name) + r'$', text, re.M):
            raise ValueError(f'{target}: {name} exists without CablePort; inspect manually')
        go_doc = src[go][1]
        comps = re.findall(r'^  - component: \{fileID: (-?\d+)\}$', go_doc, re.M)
        transforms = [fid for fid in comps if src[fid][0] in (4, 224)]
        colliders = [fid for fid in comps if src[fid][0] == 135]
        if len(comps) != 3 or len(transforms) != 1 or len(colliders) != 1 or port not in comps:
            raise ValueError(f'{source}/{name}: expected transform, sphere, CablePort only')
        tr, sphere = transforms[0], colliders[0]
        if reference(src[tr][1], 'm_Father') != src_root:
            raise ValueError(f'{source}/{name}: port is not a direct child of the Item')
        pivot_tr = reference(src[port][1], 'snapPivot')
        pivot_go = reference(src[pivot_tr][1], 'm_GameObject')
        if reference(src[pivot_tr][1], 'm_Father') != tr:
            raise ValueError(f'{source}/{name}: Snap Pivot is not a child of the port')
        if re.findall(r'^  - component: \{fileID: (-?\d+)\}$', src[pivot_go][1], re.M) != [pivot_tr]:
            raise ValueError(f'{source}/{name}: pivot contains extra components')
        replacements = dict(zip((go, tr, sphere, port, pivot_go, pivot_tr),
                                new_ids(used, target, name)))
        replacements[src_owner] = dst_owner
        replacements[src_root] = dst_root
        # Do not copy the decorative socket model: the target has its own mesh.
        for fid in (go, tr, sphere, port, pivot_go, pivot_tr):
            doc = clone_doc(src[fid][1], fid, replacements[fid], replacements)
            if fid == tr:
                doc, count = re.subn(r'(?m)^  m_Children:(?: \[\]\n|\n(?:  - \{fileID: -?\d+\}\n)*)',
                                     '  m_Children:\n  - {fileID: ' + replacements[pivot_tr] + '}\n', doc, count=1)
                if count != 1:
                    raise ValueError(source + '/' + name + ': missing child list')
            elif fid == pivot_tr:
                # A designer's pivot can itself contain marker meshes; only
                # its transform belongs to the portable socket geometry.
                doc, count = re.subn(r'(?m)^  m_Children:(?: \[\]\n|\n(?:  - \{fileID: -?\d+\}\n)*)',
                                     '  m_Children: []\n', doc, count=1)
                if count != 1:
                    raise ValueError(source + '/' + name + ': missing pivot child list')
            appended.append(doc)
        if '  m_Children: []\n' in root_text:
            root_text = root_text.replace('  m_Children: []\n',
                                          '  m_Children:\n  - {fileID: ' + replacements[tr] + '}\n', 1)
        else:
            root_text, count = re.subn(r'(?m)^  m_Children:\n(?:  - \{fileID: -?\d+\}\n)*',
                                      lambda m: m.group(0) + '  - {fileID: ' + replacements[tr] + '}\n',
                                      root_text, count=1)
            if count != 1:
                raise ValueError(target + ': missing root children')
        added.append(name)
    if not added:
        return []
    text = text.replace(dst[dst_root][1], root_text, 1)
    path.write_text(text.rstrip() + '\n' + ''.join(appended))
    return added


def child_transforms(doc):
    return re.findall(r'^  - \{fileID: (-?\d+)\}$', doc, re.M)


def append_child(parent_doc, child):
    if '  m_Children: []\n' in parent_doc:
        return parent_doc.replace('  m_Children: []\n',
                                  '  m_Children:\n  - {fileID: ' + child + '}\n', 1)
    new, count = re.subn(r'(?m)^  m_Children:\n(?:  - \{fileID: -?\d+\}\n)*',
                         lambda m: m.group(0) + '  - {fileID: ' + child + '}\n',
                         parent_doc, count=1)
    if count != 1:
        raise ValueError('missing parent child list')
    return new


def replicate_markers(source, target):
    """Append author's direct Conector/Cube children only to generated ports."""
    source_docs = blocks((ROOT / (source + '.prefab')).read_text())
    path = ROOT / (target + '.prefab')
    text = path.read_text()
    target_docs = blocks(text)
    source_ports = authored_ports(source_docs)
    target_ports = authored_ports(target_docs)
    used = set(target_docs)
    appended = []
    updated = {}
    copied = []
    for port_name, (source_go, source_port) in source_ports.items():
        if port_name not in target_ports:
            continue
        target_go, _ = target_ports[port_name]
        # Never modify a target port that the designer authored independently.
        if target_go != new_ids(set(), target, port_name)[0]:
            continue
        source_tr = next(fid for fid in re.findall(r'^  - component: \{fileID: (-?\d+)\}$',
                                                  source_docs[source_go][1], re.M)
                         if source_docs[fid][0] in (4, 224))
        target_tr = next(fid for fid in re.findall(r'^  - component: \{fileID: (-?\d+)\}$',
                                                  target_docs[target_go][1], re.M)
                         if target_docs[fid][0] in (4, 224))
        parent_text = updated.get(target_tr, target_docs[target_tr][1])
        siblings = child_transforms(parent_text)
        sibling_names = {field(target_docs[reference(target_docs[t][1], 'm_GameObject')][1], 'm_Name')
                         for t in siblings}
        for source_child in child_transforms(source_docs[source_tr][1]):
            child_doc = source_docs[source_child][1]
            if '  m_GameObject:' not in child_doc:
                continue  # prefab-instance marker requires its own authored asset
            child_go = reference(child_doc, 'm_GameObject')
            label = field(source_docs[child_go][1], 'm_Name')
            if label not in ('Conector', 'Cube') or label in sibling_names:
                continue
            if child_transforms(child_doc):
                raise ValueError(f'{source}/{port_name}/{label}: nested marker; inspect manually')
            components = re.findall(r'^  - component: \{fileID: (-?\d+)\}$',
                                    source_docs[child_go][1], re.M)
            if source_child not in components:
                raise ValueError(f'{source}/{port_name}/{label}: missing transform component')
            mapping = {source_tr: target_tr}
            for fid in (child_go, *components):
                salt = 0
                while True:
                    digest = hashlib.sha256(f'{target}/{port_name}/{label}/{fid}/{salt}'.encode()).digest()
                    new_fid = str(int.from_bytes(digest[:8], 'big') % (2**62 - 1) + 10**16)
                    if new_fid not in used:
                        used.add(new_fid)
                        mapping[fid] = new_fid
                        break
                    salt += 1
            for fid in (child_go, *components):
                appended.append(clone_doc(source_docs[fid][1], fid, mapping[fid], mapping))
            parent_text = append_child(parent_text, mapping[source_child])
            sibling_names.add(label)
            copied.append(f'{port_name}/{label}')
        if parent_text != target_docs[target_tr][1]:
            updated[target_tr] = parent_text
    if not appended:
        return []
    for fid, new_doc in updated.items():
        text = text.replace(target_docs[fid][1], new_doc, 1)
    path.write_text(text.rstrip() + '\n' + ''.join(appended))
    return copied


def replicate_board_marker(target):
    """Copy the authored ATX HDMI indicator, a nested FBX prefab instance."""
    source = blocks((ROOT / 'ATX.prefab').read_text())
    path = ROOT / (target + '.prefab')
    text = path.read_text()
    dest = blocks(text)
    old_port = authored_ports(source)['Board video'][1]
    new_go, new_port = authored_ports(dest)['Board video']
    if new_go != new_ids(set(), target, 'Board video')[0]:
        return []  # author-owned target: never overwrite
    old_pivot = reference(source[old_port][1], 'snapPivot')
    new_pivot = reference(dest[new_port][1], 'snapPivot')
    if child_transforms(dest[new_pivot][1]):
        return []
    old_children = child_transforms(source[old_pivot][1])
    if len(old_children) != 1 or ' stripped' not in source[old_children[0]][1].splitlines()[0]:
        raise ValueError('ATX Board video: expected one imported HDMI marker')
    old_tr = old_children[0]
    old_instance = reference(source[old_tr][1], 'm_PrefabInstance')
    used = set(dest)
    ids = []
    for part in ('instance', 'stripped-transform'):
        salt = 0
        while True:
            digest = hashlib.sha256(f'{target}/Board video/hdmi/{part}/{salt}'.encode()).digest()
            fid = str(int.from_bytes(digest[:8], 'big') % (2**62 - 1) + 10**16)
            if fid not in used:
                used.add(fid)
                ids.append(fid)
                break
            salt += 1
    new_instance, new_tr = ids
    replacements = {old_pivot: new_pivot, old_instance: new_instance, old_tr: new_tr}
    pivot_doc = append_child(dest[new_pivot][1], new_tr)
    text = text.replace(dest[new_pivot][1], pivot_doc, 1)
    text = text.rstrip() + '\n'
    text += clone_doc(source[old_instance][1], old_instance, new_instance, replacements)
    text += clone_doc(source[old_tr][1], old_tr, new_tr, replacements)
    path.write_text(text)
    return ['Board video/hdmi indicator']


def main():
    for source, targets in FAMILIES.items():
        for target in targets:
            names = replicate(source, target)
            markers = replicate_markers(source, target)
            if source == 'ATX':
                markers += replicate_board_marker(target)
            result = names + markers
            print(f'{source} -> {target}: ' + (', '.join(result) if result else 'already complete'))


if __name__ == '__main__':
    main()
