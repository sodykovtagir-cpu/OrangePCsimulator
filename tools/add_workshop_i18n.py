def main():
    path = Path("/home/user/OrangePCsimulator/Assets/Resources/Translate.txt")
    raw = path.read_text(encoding="utf-8")
    if not raw.endswith("\n"):
        raw += "\n"
    existing = {ln.split("\t")[0] for ln in raw.splitlines() if ln.strip()}
    header = raw.splitlines()[0].split("\t")
    assert header[1:] == LANGS, (header[1:], LANGS)

    new_lines = []
    skipped = []
    for key, d in T.items():
        if key in existing:
            skipped.append(key)
            continue
        cols = [key]
        for lang in LANGS:
            cols.append(d.get(lang, d["EN"]))
        # no tabs/newlines inside cells
        cols = [c.replace("\t", " ").replace("\n", " ").replace("\r", "") for c in cols]
        new_lines.append("\t".join(cols))

    path.write_text(raw + "\n".join(new_lines) + ("\n" if new_lines else ""), encoding="utf-8")
    print("added", len(new_lines), "skipped", len(skipped))
    if skipped:
        print("skipped keys:", skipped)


if __name__ == "__main__":
    main()
